-- Enable Postgres Changes for public.orders so admin telemetry can refresh on
-- real database changes instead of polling every few seconds.

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'orders'
  ) then
    alter publication supabase_realtime add table public.orders;
  end if;
end $$;
